#[cfg_attr(not(feature = "window"), allow(dead_code))]
impl DemoTerrain {
    /// Global sample `(sx, sz)` (range `first_sample..first+dim`).
    fn index(&self, sx: i32, sz: i32) -> Option<usize> {
        let ix = sx - self.first_sample;
        let iz = sz - self.first_sample;
        let dim = self.dim as i32;
        if ix < 0 || iz < 0 || ix >= dim || iz >= dim {
            return None;
        }
        Some(iz as usize * self.dim + ix as usize)
    }

    /// Raw sampler height at a global sample (for the probe).
    pub fn raw_at(&self, sx: i32, sz: i32) -> Option<f32> {
        self.index(sx, sz).map(|at| self.raw[at])
    }

    /// Mesh surface height at `(x, z)` (bilinear, clamped).
    pub fn height_at(&self, x: f32, z: f32) -> f32 {
        let sx = x / SAMPLE_SPACING_M;
        let sz = z / SAMPLE_SPACING_M;
        let last = (self.dim - 1) as f32;
        let fx = (sx - self.first_sample as f32).clamp(0.0, last);
        let fz = (sz - self.first_sample as f32).clamp(0.0, last);
        let ix = fx.floor() as usize;
        let iz = fz.floor() as usize;
        let ix1 = (ix + 1).min(self.dim - 1);
        let iz1 = (iz + 1).min(self.dim - 1);
        let tx = fx - ix as f32;
        let tz = fz - iz as f32;
        let at = |x: usize, z: usize| self.heights[z * self.dim + x];
        let h00 = at(ix, iz);
        let h10 = at(ix1, iz);
        let h01 = at(ix, iz1);
        let h11 = at(ix1, iz1);
        let top = h00 + (h10 - h00) * tx;
        let bottom = h01 + (h11 - h01) * tx;
        top + (bottom - top) * tz
    }

    /// Band of the sample nearest to `(x, z)`.
    pub fn band_at(&self, x: f32, z: f32) -> TerrainBand {
        let ix = (x / SAMPLE_SPACING_M).round() as i32;
        let iz = (z / SAMPLE_SPACING_M).round() as i32;
        self.index(ix, iz)
            .map(|at| self.bands[at])
            .unwrap_or(TerrainBand::Land)
    }

    /// Outer side of the ring in metres.
    pub fn outer_m(&self) -> f32 {
        self.first_sample as f32 * SAMPLE_SPACING_M + self.dim as f32 * SAMPLE_SPACING_M
    }

    /// Inner (negative) side of the ring in metres.
    pub fn inner_neg_m(&self) -> f32 {
        self.first_sample as f32 * SAMPLE_SPACING_M
    }

    /// Samples per band (`ocean`, `beach`, `land`).
    pub fn band_counts(&self) -> (usize, usize, usize) {
        let mut counts = (0usize, 0usize, 0usize);
        for band in &self.bands {
            match band {
                TerrainBand::Ocean => counts.0 += 1,
                TerrainBand::Beach => counts.1 += 1,
                TerrainBand::Land => counts.2 += 1,
            }
        }
        counts
    }
}

