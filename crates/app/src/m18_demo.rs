//! M18 — composition of the **integrated demo** and anti-screen probe
//! `DEMO-001`.
//!
//! A single composition, two consumers:
//! - the **window** `m18_window` (feature `window`) mounts the Bevy scene with
//!   this composition (textured retail city + terrain + NPCs + M17 UI);
//! - the **probe** `--probe DEMO-001` runs the SAME composition headless
//!   (0 GPU) and verifies counts, determinism ×2, bit-exact sampler and
//!   absence of ARENA2 ⇒ exit 2.
//!
//! Composed layers (in the incremental ORDER order):
//! - **D1** retail city: `MAPS.BSA` + `BLOCKS.BSA` + `ARCH3D.BSA` through the
//!   M10 API (`compose_capital_with_pixel`) + M12 `TEXTURE.*` textures
//!   (`split_by_texture` + `texture::decode_frame` + `Palette::to_rgba`);
//! - **D2** terrain: bit-exact M13 sampler `WoodsMap::sample_grid` over a
//!   ring of [`TERRAIN_RING`] samples around the city (mesh per
//!   ocean/beach/land band). The vertical datum is anchored at the city
//!   centre and blended with `smoothstep` up to [`TERRAIN_BLEND_M`] — this is
//!   a **demo composition** decision (the city lives at y=0), not a
//!   modification of the sampler: the raw values stay in `raw` and the probe
//!   contrasts them against `sample_grid`;
//! - **D3** M15 NPCs: `NpcWorld::populate` (NAMEGEN.DAT + TEXTURE.256 +
//!   TEXT.RSC) with the flat decoded to RGBA and a retail caption;
//! - **D4** M17 UI: the panels of `ui_assets::session_panels` composed
//!   on the 320×200 canvas with transparency (index 0 ⇒ alpha 0) so they can
//!   be overlaid (4 1996 panels + the 2 map panels of B3-c = 6);
//! - **D5** M20 character (spec §9): `CLASS01.CFG` → [`Career`] →
//!   [`Character::starting`] with the [`M19_SEED`] seed and `BIO.DAT` →
//!   [`Biography`]. The **live HUD** is the status line rendered with the
//!   retail `.FNT` (`FONT0000.FNT`) and re-generated by
//!   [`DemoScene::m20_refresh_hud`] every time the character changes.
//!   Progression runs **only** through
//!   [`daggerfall_skills::progression::SkillDriver`]: `m20_skill_use` (driver
//!   uses + minute, HUD digest before/after the `Running` rise),
//!   `m20_progression` (real signals → the DFU use literals), `m20_levelup`
//!   (raise sum ⇒ level 2 with the measured HP/pool applied; cap 100 and
//!   mastery 95/100) and `m20_career_humanoid` (retail `CLASS02.CFG` ⇒
//!   [`HumanoidProfile`] at levels 1/10/14/20 for M25).
//! - **M21** (spec §8): 5 measurable blocks over the real core — `K` loot
//!   inventory with a fixed seed (weight §2.5), Claymore↔Buckler equipment
//!   (GV-EQP-03/04), durability −20 exact + measured % (erratum D-M21-5),
//!   smithy repair (GV-DUR-09/12) and reuse of `PROBE-ITEM-001`/`PROBE-LOOT-001`;
//!   the M21 state is local to the blocks (0 enters the scenario digest).
//! - **M22** (spec §7): 5 measurable blocks of the first combat over the real
//!   core — real equipped weapon → damage → HP drops in the HUD (+ §7.2
//!   counter of 100 swings `chance=35` within [25,45]), Longsword wear −2
