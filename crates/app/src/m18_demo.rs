/// Composition error: missing retail data (exit 2) vs invalid data
/// (exit 1).
#[derive(Debug)]
pub enum DemoError {
    /// ARENA2 or a mandatory retail file is missing.
    MissingData(String),
    /// The data is present but does not compose (parse/validation).
    Invalid(String),
}

impl std::fmt::Display for DemoError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::MissingData(reason) => write!(f, "retail data missing: {reason}"),
            Self::Invalid(reason) => write!(f, "invalid composition: {reason}"),
        }
    }
}

impl std::error::Error for DemoError {}

