    #[test]
    fn m20_digest_changes_with_character_and_hud() {
        let mut character =
            Character::starting(synthetic_spellsword(), &mut Rng64::new(M19_SEED), 1);
        let before = m20_character_digest(&character);
        let mut driver = SkillDriver::new(M19_SEED);
        driver.use_skill(&mut character, Skill::Running, 109);
        assert_eq!(
            before,
            m20_character_digest(&character),
            "pending uses do not enter the digest (only permanent skills/state)"
        );
        let step = driver.minute(
            &mut character,
            SKILL_CHECK_INTERVAL_MINUTES + 1,
            &MotionSignals::default(),
        );
        assert!(step.checked, "the 360 min gate must open at 361");
        assert_eq!(character.live_skill(Skill::Running), 6);
        assert_ne!(before, m20_character_digest(&character), "a permanent skill changes the digest");

        let font = synthetic_font(false);
        let ink = [255u8, 255, 255];
        let hud_before = caption_texture(&font, ink, "SPELLSWORD - LV 1 - RUN 5");
        let hud_after = caption_texture(&font, ink, "SPELLSWORD - LV 1 - RUN 6");
        assert_ne!(m20_rgba_digest(&hud_before.rgba), m20_rgba_digest(&hud_after.rgba));
    }
