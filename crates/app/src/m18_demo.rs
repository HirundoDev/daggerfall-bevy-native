//! `DEMO-001`.
//!
//! A single composition, two consumers:
//! - the **window** `m18_window` (feature `window`) mounts the Bevy scene with
//!   this composition (textured retail city + terrain + NPCs + M17 UI);
//! - the **probe** `--probe DEMO-001` runs the SAME composition headless
//!   (0 GPU) and verifies counts, determinism ×2, bit-exact sampler and
//!   absence of ARENA2 ⇒ exit 2.
